"""
Run the full pipeline (segmentation -> lobe typing -> both classifiers ->
crop) across every raw frame in data/sample/Set1, and write out:

- data/generated_dataset/budding/*.tif, non_budding/*.tif -- crops, labeled
  by the modern (convexity-defect) classifier, since that's the pipeline
  we're taking forward. (Not the original training_set/testing_set --
  per instruction, this is a fresh dataset generated by our own code.)
- data/generated_dataset/manifest.csv -- one row per classifiable cell,
  with both classifiers' verdicts, so classical-vs-modern agreement can
  be audited later without re-running everything.

multicell / ambiguous blobs are recorded in the manifest (included=False)
but no crop is saved for them -- consistent with excluding them from
training, same as the original data's separate multicell folder.
"""
import csv
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent / "src"))

import tifffile

from segmentation import segment
from features import analyze_frame
from modern_classifier import analyze_frame_modern

ROOT = Path(__file__).parent.parent
RAW_DIR = ROOT / "data" / "sample" / "Set1"
OUT_DIR = ROOT / "data" / "generated_dataset"


def main():
    (OUT_DIR / "budding").mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "non_budding").mkdir(parents=True, exist_ok=True)

    manifest_path = OUT_DIR / "manifest.csv"
    t0 = time.time()
    n_saved = 0

    with open(manifest_path, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow([
            "frame", "cell_label", "centroid_x", "centroid_y", "area",
            "blob_type", "included",
            "classical_zero_crossings", "classical_budding",
            "modern_defect_ratio", "modern_budding",
            "classifiers_agree", "crop_path",
        ])

        for frame in range(1, 101):
            raw = tifffile.imread(RAW_DIR / f"Image{frame}.tif")
            mask = segment(raw)
            baseline = {r.label: r for r in analyze_frame(mask, raw)}
            modern = {r.label: r for r in analyze_frame_modern(mask, raw)}

            for lbl, b in baseline.items():
                m = modern.get(lbl)
                agree = (b.budding == m.budding) if (b.included and m and m.included) else ""
                crop_path = ""

                if b.included and m is not None and m.included and m.crop is not None:
                    subdir = "budding" if m.budding else "non_budding"
                    fname = f"frame{frame}_cell{lbl}.tif"
                    tifffile.imwrite(OUT_DIR / subdir / fname, m.crop)
                    crop_path = f"{subdir}/{fname}"
                    n_saved += 1

                writer.writerow([
                    frame, lbl, round(b.centroid_xy[0], 1), round(b.centroid_xy[1], 1),
                    b.area, b.blob_type, b.included,
                    b.zero_crossings, b.budding,
                    round(m.features.max_defect_depth_ratio, 3) if m else "", m.budding if m else "",
                    agree, crop_path,
                ])

            print(f"frame {frame} done, {n_saved} crops saved so far, elapsed {time.time()-t0:.1f}s", flush=True)

    print(f"DONE. {n_saved} crops saved. manifest at {manifest_path}")


if __name__ == "__main__":
    main()
